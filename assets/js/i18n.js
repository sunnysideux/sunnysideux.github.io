  function mergeTranslation(base, translation) {
    if (translation === undefined) return base;

    if (Array.isArray(base) && Array.isArray(translation)) {
      return base.map((item, index) => mergeTranslation(item, translation[index]));
    }

    if (base && typeof base === "object" && translation && typeof translation === "object") {
      const result = { ...base };
      Object.keys(translation).forEach((key) => {
        result[key] = mergeTranslation(base[key], translation[key]);
      });
      return result;
    }

    return translation;
  }

